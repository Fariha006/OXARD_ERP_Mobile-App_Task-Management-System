import React, { useState, useEffect } from 'react';
import { View, Text, StyleSheet, ScrollView, TouchableOpacity, Image, SafeAreaView, ActivityIndicator } from 'react-native';
import { getEligibilityData } from '../api/api';
import UserStorage from '../utils/userStorage';

const ACCORDIONS = [
  { key: 'accruals', label: 'Accruals', item: 'Item1', field: 'Employee Accruals' },
  { key: 'leaves', label: 'Leaves', item: 'Item2', field: 'Employee Leave' },
];

export default function EligibilitiesScreen({ navigation }: { navigation?: any }) {
  const [data, setData] = useState<any>({});
  const [loading, setLoading] = useState(true);
  const [error, setError] = useState<string | null>(null);
  const [openIndexes, setOpenIndexes] = useState<string[]>(['accruals']);

  useEffect(() => {
    const fetchData = async () => {
      setLoading(true);
      setError(null);
      try {
        const token = await UserStorage.getToken();
        if (!token) {
          setError('No authentication token found. Please login again.');
          setLoading(false);
          return;
        }
        const result = await getEligibilityData(token);
        setData(result || {});
      } catch (err) {
        setError('Failed to fetch data');
      } finally {
        setLoading(false);
      }
    };
    fetchData();
  }, []);

  const toggleAccordion = (key: string) => {
    setOpenIndexes(openIndexes.includes(key)
      ? openIndexes.filter(i => i !== key)
      : [...openIndexes, key]);
  };

  if (loading) {
    return (
      <SafeAreaView style={styles.container}>
        <View style={styles.loadingContainer}>
          <ActivityIndicator size="large" color="#133F7C" />
          <Text style={styles.loadingText}>Loading eligibilities...</Text>
        </View>
      </SafeAreaView>
    );
  }

  if (error) {
    return (
      <SafeAreaView style={styles.container}>
        <View style={styles.errorContainer}>
          <Text style={styles.errorText}>{error}</Text>
        </View>
      </SafeAreaView>
    );
  }

  return (
    <SafeAreaView style={styles.container}>
      <View style={[styles.back, styles.toptitle]}>
        <TouchableOpacity onPress={() => navigation?.goBack && navigation.goBack()}>
          <View style={styles.backicon}>
            <Image source={require('../../assets/images/backarow.png')}
              style={styles.backiconimg} resizeMode="contain" />
          </View>
        </TouchableOpacity>
        <View style={styles.pagewrap}>
          <Text style={styles.pagetitle}>Eligibilities</Text>
        </View>
        <TouchableOpacity style={styles.rightclick}></TouchableOpacity>
      </View>
      <ScrollView contentContainerStyle={styles.scrollContainer}>
        {ACCORDIONS.map(({ key, label, item, field }) => (
          <View key={key} style={styles.accordion}>
            <TouchableOpacity style={[styles.accordionHeader, openIndexes.includes(key) ? styles.accordionHeaderOpen : styles.accordionHeaderClosed]}  
            onPress={() => toggleAccordion(key)}>
              <View style={styles.hdrltficn}>
                <Image source={require('../../assets/images/innerpage/star.png')} style={[styles.ltficn, styles.star]} resizeMode="contain" />
                <Text style={styles.accordionTitle}>{label}</Text>
              </View>
              <Text>{openIndexes.includes(key) ? '▲' : '▼'}</Text>
            </TouchableOpacity>
            {openIndexes.includes(key) && (
              <View style={styles.accordionContent}>
                {Array.isArray(data?.[item]) && data[item].length === 0 && (
                  <Text style={styles.lbl}>No data found.</Text>
                )}
                {Array.isArray(data?.[item]) && data[item].map((d: any, idx: number) => (
                  <View key={idx} style={idx % 2 === 0 ? styles.odd : styles.even}>
                    <Text style={styles.vlue}>{d[field]}</Text>
                  </View>
                ))}
              </View>
            )}
          </View>
        ))}
      </ScrollView>
    </SafeAreaView>
  );
}

